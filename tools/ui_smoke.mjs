    const path=resolve(root,decodeURIComponent(new URL(req.url,'http://localhost').pathname).slice(1));
    if(!path.startsWith(root+sep)){res.writeHead(403);res.end();return;}
    const body=await readFile(path);
    res.writeHead(200,{'Content-Type':({'.html':'text/html','.js':'text/javascript','.css':'text/css','.png':'image/png','.svg':'image/svg+xml','.json':'application/json'})[extname(path)]||'text/plain'});
